def set_run_font(run, font_name='宋体', font_size=12, bold=False):
    run.font.size = Pt(font_size)
    run.font.bold = bold
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)

def add_heading_paragraph(doc, text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(12 if level == 1 else 6)
    p.paragraph_format.space_after = Pt(6)
    if level == 1:
        run = p.add_run(text)
        set_run_font(run, font_size=16, bold=True)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif level == 2:
        run = p.add_run(text)
        set_run_font(run, font_size=14, bold=True)
    else:
        run = p.add_run(text)
        set_run_font(run, font_size=12, bold=True)
    return p

def add_body_paragraph(doc, text, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(3)
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    run = p.add_run(text)
    set_run_font(run, font_size=12, bold=False)
    return p

