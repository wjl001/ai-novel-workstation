def set_font(run, size=10.5, bold=False, color=COLOR_DARK):
    run.font.name = FONT_NAME
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    r = run._element
    rPr = r.find(qn('w:rPr'))
    if rPr is None:
        rPr = parse_xml(f'<w:rPr {nsdecls("w")}></w:rPr>')
        r.insert(0, rPr)
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = parse_xml(f'<w:rFonts {nsdecls("w")} w:eastAsia="{FONT_NAME}" w:ascii="{FONT_NAME}" w:hAnsi="{FONT_NAME}"/>')
        rPr.insert(0, rFonts)
    else:
        rFonts.set(qn('w:eastAsia'), FONT_NAME)
        rFonts.set(qn('w:ascii'), FONT_NAME)
        rFonts.set(qn('w:hAnsi'), FONT_NAME)

def set_para_fmt(para, align=WD_ALIGN_PARAGRAPH.LEFT, sb=0, sa=6, ls=1.5, fli=None):
    para.alignment = align
    pf = para.paragraph_format
    pf.space_before = Pt(sb)
    pf.space_after = Pt(sa)
    pf.line_spacing = ls
    if fli:
        pf.first_line_indent = Pt(fli)

def add_h(text, level=1):
    para = doc.add_paragraph()
    if level == 1:
        set_para_fmt(para, WD_ALIGN_PARAGRAPH.LEFT, 18, 12, 1.3)
        run = para.add_run(text)
