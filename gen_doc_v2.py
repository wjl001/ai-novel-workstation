def add_bullet(text, level=0, prefix=None):
    para = doc.add_paragraph()
    set_para_fmt(para, WD_ALIGN_PARAGRAPH.LEFT, 0, 4, 1.5)
    pf = para.paragraph_format
    pf.left_indent = Pt(21 + level * 21)
    pf.first_line_indent = Pt(-12)
    bc = '● ' if level == 0 else '○ ' if level == 1 else '▪ '
    run = para.add_run(bc)
    set_font(run, 10.5, True, COLOR_PRIMARY if level == 0 else COLOR_SECONDARY)
    if prefix:
        r2 = para.add_run(prefix)
        set_font(r2, 10.5, True, COLOR_DARK)
    r3 = para.add_run(text)
    set_font(r3, 10.5, False, COLOR_DARK)
    return para

def add_table(headers, rows, widths=None, hcolor='4F46E5'):
    table = doc.add_table(rows=1+len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'
    hc = table.rows[0].cells
    for i, h in enumerate(headers):
        hc[i].text = ''
        p = hc[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        set_font(r, 10, True, COLOR_WHITE)
        shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hcolor}"/>')
        hc[i]._element.get_or_add_tcPr().append(shd)
        hc[i].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    for ri, rd in enumerate(rows):
        rc = table.rows[ri+1].cells
        for ci, ct in enumerate(rd):
            rc[ci].text = ''
            p = rc[ci].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r = p.add_run(str(ct))
            set_font(r, 9.5, False, COLOR_DARK)
            rc[ci].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            if ri % 2 == 1:
                shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="F8FAFC"/>')
                rc[ci]._element.get_or_add_tcPr().append(shd)
    if widths:
        for i, w in enumerate(widths):
            for row in table.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table

def add_img(path, caption, w=6.0):
    if os.path.exists(path):
        para = doc.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = para.add_run()
        run.add_picture(path, width=Inches(w))
        cp = doc.add_paragraph()
        set_para_fmt(cp, WD_ALIGN_PARAGRAPH.CENTER, 2, 10, 1.2)
        cr = cp.add_run(caption)
        set_font(cr, 9, True, COLOR_GRAY)
    else:
        add_p(f'[图表缺失: {caption}]', indent=False, color=COLOR_DANGER)

def add_callout(text, ctype='info'):
    colors = {'info':('E0F2FE','0EA5E9','提示'),'warning':('FEF3C7','F59E0B','注意'),
              'danger':('FEE2E2','EF4444','重要'),'success':('D1FAE5','10B981','说明')}
    bg, border, label = colors.get(ctype, colors['info'])
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.rows[0].cells[0]
    cell.text = ''
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{bg}"/>')
    cell._element.get_or_add_tcPr().append(shd)
    tcB = parse_xml(f'<w:tcBorders {nsdecls("w")}><w:left w:val="single" w:sz="24" w:color="{border}"/></w:tcBorders>')
    cell._element.get_or_add_tcPr().append(tcB)
    p = cell.paragraphs[0]
    set_para_fmt(p, WD_ALIGN_PARAGRAPH.LEFT, 4, 4, 1.5)
    r1 = p.add_run(f'【{label}】')
    set_font(r1, 10, True, RGBColor(int(border[0:2],16),int(border[2:4],16),int(border[4:6],16)))
    r2 = p.add_run(text)
    set_font(r2, 10, False, COLOR_DARK)
    doc.add_paragraph()

