    s = OxmlElement('w:shd'); s.set(qn('w:fill'),'%02X%02X%02X'%color); c._tc.get_or_add_tcPr().append(s)
    if content:
        p2 = c.add_paragraph(); p2.alignment=WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(content); sf(r2, size=9, color=(255,255,255))

